const fail = (substage = 'OUTPUT_VALIDATION', diagnostics = []) => {
  const error = new Error(`Windows authority helper build failed [win-authority:BUILD_COMPILER:${substage}]`);
  error.stage = 'BUILD_COMPILER';
  error.substage = substage;
  error.code = substage;
  error.diagnostics = Object.freeze([...diagnostics]);
  throw error;
};
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

// These records are generated by this parent, never copied from node-gyp or
// the hosted toolchain. Their fixed vocabulary and count provide coarse CI
// liveness without disclosing paths, environment, or arbitrary build output.
const nativeRebuildEvidence = value => {
  process.stderr.write(`[win-authority:BUILD_COMPILER:NATIVE_REBUILD:${value}]\n`);
};

const BUILD_DIAGNOSTIC_LIMIT = 8;
const diagnosticRecord = (file, line, code) => `${file}:${line}:${code}`;

// node-gyp output contains checkout paths, SDK paths, user profiles and the
// complete inherited build environment. Preserve only a bounded compiler
// location/code tuple rooted at the committed source basename.
export const sanitizeWindowsNativeBuildDiagnostics = output => {
  const text = Buffer.isBuffer(output) ? output.toString('utf8') : typeof output === 'string' ? output : '';
  const diagnostics = [];
  const seen = new Set();
  const patterns = [
    /(?:^|[\\/])(propr_windows_launcher\.cc)\((\d+)(?:,\d+)?\)\s*:\s*(?:fatal\s+)?error\s+(C\d{4})\b/gim,
    /(?:^|[\\/])(propr_windows_launcher\.(?:cc|obj))\s*:\s*(?:fatal\s+)?error\s+(LNK\d{4})\b/gim,
    /\b(?:fatal\s+)?error\s+(LNK\d{4})\b/gim,
  ];
  for (const pattern of patterns) {
    for (const match of text.matchAll(pattern)) {
      const value = match[3]
        ? diagnosticRecord(match[1], match[2], match[3].toUpperCase())
        : match[2]
          ? diagnosticRecord(match[1], '0', match[2].toUpperCase())
          : diagnosticRecord('link', '0', match[1].toUpperCase());
      if (!seen.has(value)) {
        seen.add(value);
        diagnostics.push(value);
      }
      if (diagnostics.length === BUILD_DIAGNOSTIC_LIMIT) return Object.freeze(diagnostics);
    }
  }
  return Object.freeze(diagnostics);
};

export const classifyWindowsNativeBuildFailure = error => {
  const code = error && typeof error === 'object' ? error.code : undefined;
  if (code === 'EINVAL' || code === 'ENOENT' || code === 'EACCES' || code === 'EPERM') return 'SPAWN';
  if (code === 'ERR_CHILD_PROCESS_STDIO_MAXBUFFER' || error?.name === 'RangeError'
    && /maxBuffer/i.test(String(error?.message ?? ''))) return 'OUTPUT_LIMIT';
  if (error?.killed === true && error?.signal) return 'TIMEOUT';
  const diagnostics = sanitizeWindowsNativeBuildDiagnostics(`${error?.stdout ?? ''}\n${error?.stderr ?? ''}`);
  if (diagnostics.some(value => /:LNK\d{4}$/.test(value))) return 'LINK';
  if (diagnostics.some(value => /:C\d{4}$/.test(value))) return 'COMPILE';
  return 'EXIT';
};

const sameFileIdentity = (left, right) => left.dev === right.dev && left.ino === right.ino
  && left.size === right.size && left.nlink === right.nlink;

const normalDosExecutable = (path, basename) => {
  const candidate = /^\\\\\?\\[A-Za-z]:\\/.test(path) ? path.slice(4) : path;
  if (!/^[A-Za-z]:\\[^\0]+$/.test(candidate) || candidate.startsWith('\\\\')
      || windowsPath.isAbsolute(candidate) !== true || candidate.indexOf(':', 2) >= 0
      || windowsPath.basename(candidate).toLowerCase() !== basename
      || windowsPath.basename(windowsPath.dirname(candidate)).toLowerCase() !== 'system32') {
    fail('DIRECTORY_PROBE');
  }
  return candidate;
};

const normalDosPowerShell = path => {
  const candidate = /^\\\\\?\\[A-Za-z]:\\/.test(path) ? path.slice(4) : path;
  if (!/^[A-Za-z]:\\[^\0]+$/.test(candidate) || candidate.startsWith('\\\\')
      || windowsPath.isAbsolute(candidate) !== true || candidate.indexOf(':', 2) >= 0
      || !candidate.toLowerCase().endsWith('\\system32\\windowspowershell\\v1.0\\powershell.exe')) {
    fail('DIRECTORY_PROBE');
  }
  return candidate;
};

const resolveWindowsFixedOsFile = async (tool, canonicalPath) => {
  const targetStats = await lstat(tool, { bigint: true }).catch(() => fail('DIRECTORY_PROBE'));
  if (!targetStats.isFile() || targetStats.isSymbolicLink() || targetStats.nlink < 1n
      || targetStats.size <= 0n || targetStats.size > BigInt(MAX_ACL_TOOL_BYTES)) fail('DIRECTORY_PROBE');
  const target = await open(tool, fsConstants.O_RDONLY | fsConstants.O_NOFOLLOW)
    .catch(() => fail('DIRECTORY_PROBE'));
  let canonical;
  try {
    const targetBefore = await target.stat({ bigint: true }).catch(() => fail('DIRECTORY_PROBE'));
    if (!sameFileIdentity(targetBefore, targetStats)) fail('DIRECTORY_PROBE');
    canonical = canonicalPath(await realpath(tool).catch(() => fail('DIRECTORY_PROBE')));
    const canonicalStats = await lstat(canonical, { bigint: true }).catch(() => fail('DIRECTORY_PROBE'));
    if (!canonicalStats.isFile() || canonicalStats.isSymbolicLink()
        || !sameFileIdentity(canonicalStats, targetBefore)) fail('DIRECTORY_PROBE');
    const canonicalHandle = await open(canonical, fsConstants.O_RDONLY | fsConstants.O_NOFOLLOW)
      .catch(() => fail('DIRECTORY_PROBE'));
    try {
      const canonicalBefore = await canonicalHandle.stat({ bigint: true }).catch(() => fail('DIRECTORY_PROBE'));
      const targetAfter = await target.stat({ bigint: true }).catch(() => fail('DIRECTORY_PROBE'));
      const canonicalAfter = await canonicalHandle.stat({ bigint: true }).catch(() => fail('DIRECTORY_PROBE'));
      if (!sameFileIdentity(targetBefore, targetAfter) || !sameFileIdentity(targetBefore, canonicalBefore)
          || !sameFileIdentity(canonicalBefore, canonicalAfter)) fail('DIRECTORY_PROBE');
    } finally { await canonicalHandle.close().catch(() => undefined); }
  } finally { await target.close().catch(() => undefined); }
  return canonical;
};

// CreateProcess does not accept the fixed GLOBALROOT spelling. Retain the
// exact kernel-rooted file while realpath resolves its normal DOS spelling,
// then prove that spelling opens the same non-reparse OS file before launch.
export const resolveWindowsAclTool = async tool => {
  const basename = tool === KERNEL_TAKEOWN ? 'takeown.exe'
    : tool === KERNEL_ICACLS ? 'icacls.exe'
      : tool === KERNEL_WHOAMI ? 'whoami.exe' : fail('DIRECTORY_PROBE');
  return resolveWindowsFixedOsFile(tool, path => normalDosExecutable(path, basename));
};

export const invokeWindowsAclTool = async (tool, args, invoke = execFileAsync) => {
  try {
    await invoke(tool, args, {
      windowsHide: true,
      timeout: 30_000,
      maxBuffer: 64 * 1024,
      env: {},
    });
  } catch { fail('SPAWN'); }
};

const authorityAclTool = async (tool, args) => {
  const canonical = await resolveWindowsAclTool(tool);
  await invokeWindowsAclTool(canonical, args);
};

const canonicalAccountSid = value => {
  if (typeof value !== 'string') return false;
  const fields = value.split('-');
  if (fields.length !== 8 || fields[0] !== 'S' || fields[1] !== '1'
      || !((fields[2] === '5' && fields[3] === '21') || (fields[2] === '12' && fields[3] === '1'))) return false;
  return fields.slice(2).every(field => /^(?:0|[1-9]\d{0,9})$/.test(field)
    && BigInt(field) <= 0xffff_ffffn);
};

// whoami.exe is resolved from the fixed protected System32 object, receives no
// inherited environment, and returns one bounded CSV record. The account name
// is deliberately ignored: only the kernel-derived token SID is authority.
export const decodeWindowsCurrentTokenSid = output => {
  const text = Buffer.isBuffer(output) ? output.toString('utf8') : typeof output === 'string' ? output : '';
  if (Buffer.byteLength(text, 'utf8') > MAX_WHOAMI_OUTPUT_BYTES || text.includes('\0')) fail('BOOTSTRAP_AUTH');
  const match = /^(?:\ufeff)?"(?:[^"]|"")*","(S-[0-9-]+)"\r?\n?$/.exec(text);
  if (!match || !canonicalAccountSid(match[1])) fail('BOOTSTRAP_AUTH');
  return match[1];
};

export const decodeWindowsDirectoryOwnerSid = output => {
  const text = Buffer.isBuffer(output) ? output.toString('utf8') : typeof output === 'string' ? output : '';
  if (Buffer.byteLength(text, 'utf8') > MAX_WHOAMI_OUTPUT_BYTES || text.includes('\0')) fail('BOOTSTRAP_AUTH');
  const match = /^(S-[0-9-]+)\r?\n?$/.exec(text);
  if (!match || !canonicalAccountSid(match[1])) fail('BOOTSTRAP_AUTH');
  return match[1];
};

const currentWindowsTokenSid = async root => {
  const whoami = await resolveWindowsAclTool(KERNEL_WHOAMI);
  let result;
  try {
    result = await execFileAsync(whoami, ['/user', '/fo', 'csv', '/nh'], {
      windowsHide: true,
      timeout: 30_000,
      maxBuffer: MAX_WHOAMI_OUTPUT_BYTES,
      encoding: 'utf8',
      env: {},
    });
  } catch { fail('BOOTSTRAP_AUTH'); }
  if (result.stderr !== '') fail('BOOTSTRAP_AUTH');
  const sid = decodeWindowsCurrentTokenSid(result.stdout);
  const powershell = await resolveWindowsFixedOsFile(KERNEL_POWERSHELL, normalDosPowerShell);
  const rootBytes = Buffer.from(root, 'utf16le');
  if (rootBytes.length === 0 || rootBytes.length > 2048) fail('BOOTSTRAP_AUTH');
  // Cross-check the token SID against the owner takeown just assigned. Encode
  // the bounded pathname into the fixed command so PowerShell cannot reinterpret
  // it as command text, and accept only the one canonical SID output record.
  const ownerProbe = `$p=[Text.Encoding]::Unicode.GetString([Convert]::FromBase64String('${rootBytes.toString('base64')}'));`
    + '[IO.Directory]::GetAccessControl($p,[Security.AccessControl.AccessControlSections]::Owner)'
    + '.GetOwner([Security.Principal.SecurityIdentifier]).Value';
  const encodedOwnerProbe = Buffer.from(ownerProbe, 'utf16le').toString('base64');
  try {
    result = await execFileAsync(powershell,
      ['-NoLogo', '-NoProfile', '-NonInteractive', '-EncodedCommand', encodedOwnerProbe], {
      windowsHide: true,
      timeout: 30_000,
      maxBuffer: MAX_WHOAMI_OUTPUT_BYTES,
      encoding: 'utf8',
      env: {},
    });
  } catch { fail('BOOTSTRAP_AUTH'); }
  if (result.stderr !== '' || decodeWindowsDirectoryOwnerSid(result.stdout) !== sid) fail('BOOTSTRAP_AUTH');
  return sid;
};

const exactAuthorityDirectory = async root => {
  const pathStats = await lstat(root).catch(() => null);
  if (!pathStats) return false;
  if (!pathStats.isDirectory() || pathStats.isSymbolicLink()
    || (await realpath(root).catch(() => fail('DIRECTORY_PROBE'))).toLowerCase() !== resolve(root).toLowerCase()) {
    fail('DIRECTORY_PROBE');
  }
  return true;
};

// Build steps are the only writers. Reopening a previously sealed tree is an
// explicit trusted-build transition, never part of runtime authorization.
export const prepareWindowsAuthorityBuildDirectory = async (root = WINDOWS_NATIVE_AUTHORITY_DIRECTORY) => {
  if (process.platform !== 'win32') return;
  await mkdir(root, { recursive: true }).catch(() => fail('DIRECTORY_PROBE'));
  if (!(await exactAuthorityDirectory(root))) fail('DIRECTORY_PROBE');
  // Keep build ownership distinct from packaged authority: the build-only
  // bootstrap may admit this exact current owner, while the runtime bootstrap
  // must continue to reject it until sealWindowsAuthorityDirectory transfers
  // ownership to SYSTEM.
  await authorityAclTool(KERNEL_TAKEOWN, ['/F', root, '/R', '/SKIPSL']);
  const currentSid = await currentWindowsTokenSid(root);
  // /grant:r replaces only ACEs for its named trustees. Reset the complete
  // tree first so a hostile explicit trustee cannot survive build staging.
  await authorityAclTool(KERNEL_ICACLS, [root, '/reset', '/T', '/C', '/Q']);
  await authorityAclTool(KERNEL_ICACLS, [root, '/inheritance:r', '/T', '/C', '/Q']);
  await authorityAclTool(KERNEL_ICACLS, [root, '/grant:r', `${ADMINISTRATORS_SID}:(OI)(CI)F`,
    `${SYSTEM_SID}:(OI)(CI)F`, `*${currentSid}:(OI)(CI)M`, '/T', '/C', '/Q']);
  return currentSid;
};

// Hosted runners do not consistently materialize the recursive directory ACL
// transition as an exact protected child-file descriptor. Apply the same
// already-authorized principals directly to each newly created build artifact,
// with no inheritance flags, and set its owner to the fixed token SID that was
// independently derived and checked above. The build bootstrap revalidates
// every predicate from one held handle before loading the launcher.
const protectWindowsBuildArtifact = async (target, currentSid) => {
  if (!canonicalAccountSid(currentSid)) fail('BOOTSTRAP_AUTH');
  await authorityAclTool(KERNEL_ICACLS, [target, '/reset', '/Q']);
  await authorityAclTool(KERNEL_ICACLS, [target, '/inheritance:r', '/Q']);
  await authorityAclTool(KERNEL_ICACLS, [target, '/grant:r', `${ADMINISTRATORS_SID}:F`,
    `${SYSTEM_SID}:F`, `*${currentSid}:M`, '/Q']);
  await authorityAclTool(KERNEL_ICACLS, [target, '/setowner', `*${currentSid}`, '/Q']);
};

// Publish an OS-owned, protected, read/execute-only application authority.
// The verifier independently re-reads every effective explicit and inherited
// ACE from held handles; these setup operations are never accepted as proof.
export const sealWindowsAuthorityDirectory = async (root = WINDOWS_NATIVE_AUTHORITY_DIRECTORY) => {
  if (process.platform !== 'win32' || !(await exactAuthorityDirectory(root))) fail('DIRECTORY_PROBE');
  // Reset first so an explicit SID planted during the build cannot survive the
  // transition merely because /grant:r only replaces ACEs for named trustees.
  await authorityAclTool(KERNEL_ICACLS, [root, '/reset', '/T', '/C', '/Q']);
  await authorityAclTool(KERNEL_ICACLS, [root, '/inheritance:r', '/T', '/C', '/Q']);
  await authorityAclTool(KERNEL_ICACLS, [root, '/grant:r', `${SYSTEM_SID}:(OI)(CI)F`,
    `${TRUSTED_INSTALLER_SID}:(OI)(CI)F`, `${ADMINISTRATORS_SID}:(OI)(CI)RX`, '/T', '/C', '/Q']);
  await authorityAclTool(KERNEL_ICACLS, [root, '/setowner', SYSTEM_SID, '/T', '/C', '/Q']);
};

export const inspectWindowsNativeLauncherPe = (bytes, expectedArchitecture) => {
  if (!Buffer.isBuffer(bytes) || bytes.length < 512 || bytes.length > MAX_LAUNCHER_BYTES
    || bytes.readUInt16LE(0) !== 0x5a4d) fail();
  const pe = bytes.readUInt32LE(0x3c);
  if (pe < 0x40 || pe + 24 > bytes.length || bytes.toString('ascii', pe, pe + 4) !== 'PE\0\0') fail();
  const machine = bytes.readUInt16LE(pe + 4);
  const expectedMachine = expectedArchitecture === 'arm64' ? 0xaa64 : expectedArchitecture === 'x64' ? 0x8664 : -1;
  if (machine !== expectedMachine) fail();
  return { format: 'PE', architecture: expectedArchitecture, machine: expectedMachine === 0xaa64 ? 'ARM64' : 'AMD64' };
};

const heldBytes = async path => {
  const canonical = await realpath(path).catch(() => fail('OUTPUT_VALIDATION'));
  if ((process.platform === 'win32' ? canonical.toLowerCase() : canonical) !== (process.platform === 'win32'
    ? resolve(path).toLowerCase() : resolve(path))) fail('OUTPUT_VALIDATION');
  const pathStats = await lstat(path, { bigint: true }).catch(() => fail('OUTPUT_VALIDATION'));
  if (!pathStats.isFile() || pathStats.isSymbolicLink() || pathStats.nlink !== 1n
    || pathStats.size <= 0n || pathStats.size > BigInt(MAX_LAUNCHER_BYTES)) fail('OUTPUT_VALIDATION');
  const handle = await open(path, fsConstants.O_RDONLY | fsConstants.O_NOFOLLOW)
    .catch(() => fail('OUTPUT_VALIDATION'));
  try {
    const before = await handle.stat({ bigint: true });
    const bytes = await handle.readFile();
    const after = await handle.stat({ bigint: true });
    if (before.dev !== pathStats.dev || before.ino !== pathStats.ino || before.size !== pathStats.size
      || before.nlink !== 1n || after.dev !== before.dev || after.ino !== before.ino || after.size !== before.size
      || BigInt(bytes.length) !== before.size) fail('OUTPUT_VALIDATION');
    return bytes;
  } finally { await handle.close(); }
};

const publishHeldArtifact = async (target, bytes, expectedArchitecture) => {
  await rm(target, { force: true }).catch(() => fail('OUTPUT_VALIDATION'));
  const handle = await open(target, fsConstants.O_WRONLY | fsConstants.O_CREAT | fsConstants.O_EXCL, 0o600)
    .catch(() => fail('OUTPUT_VALIDATION'));
  try {
    await handle.writeFile(bytes);
    await handle.sync();
  } catch { fail('OUTPUT_VALIDATION'); }
  finally { await handle.close().catch(() => undefined); }
  const published = await heldBytes(target);
  if (!published.equals(bytes)) fail('OUTPUT_VALIDATION');
  inspectWindowsNativeLauncherPe(published, expectedArchitecture);
};

export const cleanupWindowsAuthorityBuildStaging = async (options = {}) => {
  if (process.platform !== 'win32') return;
  await rm(WINDOWS_NATIVE_BUILD_STAGING_DIRECTORY, { recursive: true, force: true })
    .catch(() => fail('LEASE'));
  await lstat(WINDOWS_NATIVE_BUILD_STAGING_DIRECTORY).then(
    () => fail('LEASE'),
    error => { if (error?.code !== 'ENOENT') fail('LEASE'); },
  );
  if (options.fault === 'after-remove') fail('LEASE');
};

let launcherBuild;

const stageWindowsNativeLauncher = async (expected, options = {}) => {
  const built = join(WINDOWS_NATIVE_LAUNCHER_SOURCE_DIRECTORY, 'build', 'Release', 'propr_windows_launcher.node');
  const builtBootstrap = join(WINDOWS_NATIVE_LAUNCHER_SOURCE_DIRECTORY, 'build', 'Release', 'propr_windows_bootstrap.node');
  const builtBuildBootstrap = join(WINDOWS_NATIVE_LAUNCHER_SOURCE_DIRECTORY, 'build', 'Release',
    'propr_windows_build_bootstrap.node');
  const bytes = await heldBytes(built);
  const bootstrapBytes = await heldBytes(builtBootstrap);
  const buildBootstrapBytes = await heldBytes(builtBuildBootstrap);
  const pe = inspectWindowsNativeLauncherPe(bytes, process.arch);
  const bootstrapPe = inspectWindowsNativeLauncherPe(bootstrapBytes, process.arch);
  const buildBootstrapPe = inspectWindowsNativeLauncherPe(buildBootstrapBytes, process.arch);
  if (expected && (expected.size !== bytes.length || expected.sha256 !== sha256(bytes)
      || expected.bootstrap.size !== bootstrapBytes.length || expected.bootstrap.sha256 !== sha256(bootstrapBytes)
      || expected.buildBootstrap.size !== buildBootstrapBytes.length
      || expected.buildBootstrap.sha256 !== sha256(buildBootstrapBytes))) fail('OUTPUT_VALIDATION');
  nativeRebuildEvidence('OUTPUT_VERIFIED');
  await prepareWindowsAuthorityBuildDirectory(WINDOWS_NATIVE_AUTHORITY_DIRECTORY);
  await prepareWindowsAuthorityBuildDirectory(WINDOWS_NATIVE_BUILD_STAGING_DIRECTORY);
  if (options.buildBootstrapOnly === true) {
    const [publishedLauncher, publishedBootstrap] = await Promise.all([
      heldBytes(WINDOWS_NATIVE_LAUNCHER), heldBytes(WINDOWS_NATIVE_BOOTSTRAP),
    ]);
    if (!publishedLauncher.equals(bytes) || !publishedBootstrap.equals(bootstrapBytes)) fail('OUTPUT_VALIDATION');
  } else {
    await publishHeldArtifact(WINDOWS_NATIVE_LAUNCHER, bytes, process.arch);
    await publishHeldArtifact(WINDOWS_NATIVE_BOOTSTRAP, bootstrapBytes, process.arch);
  }
  await publishHeldArtifact(WINDOWS_NATIVE_BUILD_BOOTSTRAP, buildBootstrapBytes, process.arch);
  // Newly created children must themselves carry protected DACLs; a protected
  // parent alone does not make a child's security descriptor authoritative.
  const authorityOwnerSid = await prepareWindowsAuthorityBuildDirectory(WINDOWS_NATIVE_AUTHORITY_DIRECTORY);
  const stagingOwnerSid = await prepareWindowsAuthorityBuildDirectory(WINDOWS_NATIVE_BUILD_STAGING_DIRECTORY);
  if (authorityOwnerSid !== stagingOwnerSid) fail('BOOTSTRAP_AUTH');
  await protectWindowsBuildArtifact(WINDOWS_NATIVE_LAUNCHER, authorityOwnerSid);
  nativeRebuildEvidence('STAGED');
  return {
    skipped: false,
    path: WINDOWS_NATIVE_LAUNCHER,
    name: 'propr-windows-launcher.node',
    size: bytes.length,
    sha256: sha256(bytes),
    bootstrap: {
      path: WINDOWS_NATIVE_BOOTSTRAP,
      name: 'propr-windows-bootstrap.node',
      size: bootstrapBytes.length,
      sha256: sha256(bootstrapBytes),
      ...bootstrapPe,
    },
    // This current-owner build capability exists only in the protected,
    // unshipped staging boundary and is removed before package sealing. It is
    // never represented in the runtime manifest.
    buildBootstrap: {
      path: WINDOWS_NATIVE_BUILD_BOOTSTRAP,
      size: buildBootstrapBytes.length,
      sha256: sha256(buildBootstrapBytes),
      ...buildBootstrapPe,
    },
    ...pe,
  };
};

const buildWindowsNativeLauncherOnce = async () => {
  if (process.platform !== 'win32') return { skipped: true };
  if (process.arch !== 'x64' && process.arch !== 'arm64') fail('OUTPUT_VALIDATION');
  await prepareWindowsAuthorityBuildDirectory();
  const nodeGyp = join(repositoryRoot, 'node_modules', 'node-gyp', 'bin', 'node-gyp.js');
  const nativeBuildDirectory = join(WINDOWS_NATIVE_LAUNCHER_SOURCE_DIRECTORY, 'build');
  let progressBucket = 0;
  nativeRebuildEvidence('STARTED');
  const progress = setInterval(() => {
    if (progressBucket >= WINDOWS_NATIVE_REBUILD_PROGRESS_BUCKETS) return;
    progressBucket += 1;
    nativeRebuildEvidence(`ACTIVE_${progressBucket}`);
  }, WINDOWS_NATIVE_REBUILD_PROGRESS_INTERVAL_MS);
  try {
    await execFileAsync(process.execPath, [nodeGyp, 'rebuild', '--directory', WINDOWS_NATIVE_LAUNCHER_SOURCE_DIRECTORY,
      `--arch=${process.arch}`], {
      cwd: repositoryRoot,
      windowsHide: true,
      timeout: WINDOWS_NATIVE_REBUILD_TIMEOUT_MS,
      killSignal: 'SIGKILL',
      maxBuffer: WINDOWS_NATIVE_REBUILD_MAX_BUFFER_BYTES,
    });
    nativeRebuildEvidence('PROCESS_COMPLETE');
  } catch (error) {
    await rm(nativeBuildDirectory, { recursive: true, force: true })
      .then(() => nativeRebuildEvidence('FAILED_CLEANED'), () => undefined);
    const diagnostics = sanitizeWindowsNativeBuildDiagnostics(`${error?.stdout ?? ''}\n${error?.stderr ?? ''}`);
    fail(classifyWindowsNativeBuildFailure(error), diagnostics);
  } finally { clearInterval(progress); }
  return stageWindowsNativeLauncher();
};

export const buildWindowsNativeLauncher = async (options = {}) => {
  if (process.platform !== 'win32') return { skipped: true };
  if (!launcherBuild) {
    launcherBuild = buildWindowsNativeLauncherOnce().catch(error => {
      launcherBuild = undefined;
      throw error;
    });
    return launcherBuild;
  }
  const built = await launcherBuild;
  return options.restage === true ? stageWindowsNativeLauncher(built, { buildBootstrapOnly: true }) : built;
};

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildWindowsNativeLauncher();
}
