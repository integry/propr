test('generatePRBody without a template is byte-identical to the historical description', async () => {
    mock.timers.enable({ apis: ['Date'], now: Date.parse('2026-10-06T08:00:00.000Z') });
    try {
        for (const result of results) {
            for (const [title, commit] of [['Fix login', 'fix: login\n\nDetails'], ['<b>Title</b>', '']]) {
                assert.equal(await generatePRBody(7, title, commit, result), legacyGeneratePRBody(7, title, commit, result));
            }
        }
    } finally {
        mock.timers.reset();
    }
});

