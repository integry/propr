function contentsOctokit(files: Record<string, string>, directories: Record<string, Array<{ name: string; path: string; type: string }>>) {
    const calls: Array<{ endpoint: string; options: Record<string, unknown> }> = [];
    return {
        calls,
        async request<T>(endpoint: string, options: Record<string, unknown>): Promise<T> {
            calls.push({ endpoint, options });
            if (endpoint === 'GET /repos/{owner}/{repo}/commits/{ref}') return { data: { sha: 'base-sha' } } as T;
            const path = String(options.path);
            if (path in files) return { data: { name: path.split('/').at(-1), path, type: 'file', encoding: 'base64', content: Buffer.from(files[path]).toString('base64') } } as T;
            if (path in directories) return { data: directories[path] } as T;
            throw Object.assign(new Error('Not Found'), { status: 404 });
        },
    };
}

test('loadPullRequestTemplate reads the template from the base branch head commit', async () => {
    const octokit = contentsOctokit({ '.propr/pr-template.md': '## run\n' }, {});
    const template = await loadPullRequestTemplate({ octokit, repoOwner: 'acme', repoName: 'app', baseBranch: 'develop' });
    assert.deepEqual(template, { kind: 'propr', path: '.propr/pr-template.md', template: { sections: { run: '' }, problems: [] } });
    assert.deepEqual(octokit.calls.map(call => call.options.ref), ['develop', 'base-sha']);
});

test('the GitHub-backed source lists directories and rejects non-file template paths', async () => {
    const octokit = contentsOctokit({ '.github/pull_request_template.md': '- [ ] tested' }, {
        '.github': [{ name: 'pull_request_template.md', path: '.github/pull_request_template.md', type: 'file' }],
    });
    const source = createGitHubPrTemplateSource(octokit, 'acme', 'app');
    assert.deepEqual(await source.listDirectory('.github', 'base-sha'), [{ name: 'pull_request_template.md', path: '.github/pull_request_template.md', type: 'file' }]);
    assert.equal(await source.listDirectory('docs', 'base-sha'), null);
    assert.deepEqual(await source.readFile('.github/pull_request_template.md', 'base-sha'), { content: '- [ ] tested' });
    assert.equal(await source.readFile('missing.md', 'base-sha'), null);
    await assert.rejects(source.readFile('.github', 'base-sha'), /regular UTF-8 file/);
});

test('continuation PRs keep their marker and default text unless a template shapes them', async () => {
    const record = { repository: 'acme/app', source_pr: 42, source_title: 'Contribution', branch_name: 'propr/continuation-pr-42', base_branch: 'main' };
    const marker = '<!-- propr-continuation:42:abc -->';
    const fallback = `${marker}\nContinuation of #42.`;
    const describe = (files: Record<string, string>, maxLength = 65536) => describeContinuationPullRequest({ octokit: contentsOctokit(files, {}), record, marker, fallback, maxLength });

    assert.equal(await describe({}), fallback);
    assert.equal(await describe({ '.propr/pr-template.md': '## summary\nContinues {{issue_title}} on {{branch}}\n## trailer\n- [ ] QA\n' }),
        `${marker}\nContinues Contribution on propr/continuation-pr-42\n\n- [ ] QA`);
    assert.equal(await describe({ '.propr/pr-template.md': '## trailer\n- [ ] QA\n' }), `${fallback}\n\n- [ ] QA`);
    assert.equal(await describe({ '.propr/pr-template.md': '## trailer\n- [ ] QA\n' }, fallback.length), fallback);
    assert.equal(await describe({ '.propr/pr-template.md': '## summary\n{{broken}}\n' }), fallback);
});

test('describeIssuePullRequestForRepository applies the base-branch template to title and body', async () => {
    const issue = { owner: 'acme', repoName: 'app', baseBranch: 'develop', branch: '7-fix', issueNumber: 7, issueTitle: 'Fix login', commitMessage: 'fix: login', claudeResult: results[2], modelName: 'claude-opus-4-5-20251101' };
    const octokit = contentsOctokit({ '.propr/pr-template.md': '## title\nfix: {{issue_title}} (#{{issue_number}})\n## summary\nCloses #{{issue_number}} in {{repository}}\n' }, {});
    const templated = await describeIssuePullRequestForRepository({ octokit, ...issue });
    assert.equal(templated.title, 'fix: Fix login (#7)');
    assert.match(templated.body, /^Closes #7 in acme\/app\n\n### 📋 Execution Summary/);
    assert.deepEqual(octokit.calls.map(call => call.options.ref), ['develop', 'base-sha']);

    const plain = await describeIssuePullRequestForRepository({ octokit: contentsOctokit({}, {}), ...issue, baseBranch: 'main' });
    assert.match(plain.title, /^\[7 by .+\] Fix login$/);
    assert.match(plain.body, /^## 🤖 AI-Generated Solution/);
});

