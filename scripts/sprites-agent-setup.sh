#!/bin/bash
# Provisions a Fly Sprite for ProPR agent runs (the Sprites agent runtime).
#
# A Sprite cannot boot the propr/agent image, so this reproduces the parts of
# it the provider entrypoints and the clone workspace transport rely on:
#   - an unprivileged `node` user with /home/node (no sudo, not in sudoers);
#   - su-exec and gosu (shims over setpriv when the Sprite has neither);
#   - node, npm and npx on root's PATH (Sprites ship them as an nvm shim that
#     sudo's secure_path drops);
#   - the agent CLIs at the versions Dockerfile.agent pins, under /opt/propr;
#   - the provider entrypoints in the root-owned /opt/propr/entrypoints, each
#     behind an `<agent>-as-agent` shim that drops to `node` BEFORE the
#     entrypoint runs, so no entrypoint ever works as root on a path the agent
#     user controls;
#   - the run launcher (/opt/propr/launcher.sh) and the empty run directory
#     (/opt/propr/run) the worker uploads each run's payload to.
#
# The runtime checkpoints the Sprite right after this script and restores that
# checkpoint after every run, so nothing here needs to clean up after a run.
#
# Usage (as root, through `sudo -n`):
#   env CLAUDE_CLI_VERSION=... CODEX_CLI_VERSION=... ANTIGRAVITY_CLI_VERSION=... \
#       ANTIGRAVITY_CLI_RELEASE_ID=... ANTIGRAVITY_CLI_SHA512=... PROPR_SPRITES_SETUP_HASH=... \
#       bash sprites-agent-setup.sh <directory the worker uploaded the setup files to>
set -euo pipefail

log() { echo "ProPR Sprite setup: $*" >&2; }
die() { log "$*"; exit 1; }

# Sprites ship Node through an nvm shim (/.sprite/bin/node) that only the
# default user's PATH contains; sudo's secure_path drops it, so root and the
# node user would have no node. Resolve the real binary and link node, npm and
# npx into <target dir> (a directory on every PATH) when node is missing.
link_sprite_node() {
    local shim="$1" target_dir="$2" real_node real_dir bin
    command -v node >/dev/null 2>&1 && return 0
    [ -x "$shim" ] || return 0
    real_node="$("$shim" -p 'process.execPath' 2>/dev/null || true)"
    if [ -z "$real_node" ] || [ ! -x "$real_node" ]; then return 0; fi
    real_dir="$(dirname "$real_node")"
    log "linking node, npm and npx from $real_dir into $target_dir"
    for bin in node npm npx; do
        if [ -e "$real_dir/$bin" ]; then ln -sf "$real_dir/$bin" "$target_dir/$bin"; fi
    done
    hash -r
}

installed_version() { "$@" --version 2>/dev/null | head -n 1 || true; }

# Installs <package>@<version> under $npm_prefix and links <bin name> into
# $bin_dir. npm 12 (on Sprites) blocks install scripts unless they are allowed,
# which leaves Claude Code without its native binary, so the pinned package's
# own scripts are allowed explicitly. Older npm versions ignore the flag.
pin_npm_cli() {
    local package="$1" version="$2" bin_name="$3"
    if ! installed_version "$npm_prefix/bin/$bin_name" | grep -qF "$version"; then
        log "installing $package@$version"
        npm install -g --no-fund --no-audit --allow-scripts="$package" --prefix "$npm_prefix" "$package@$version" >&2
    fi
    ln -sf "$npm_prefix/bin/$bin_name" "$bin_dir/$bin_name"
    installed_version "$bin_dir/$bin_name" | grep -qF "$version" || die "$bin_name is not at the pinned version $version"
}

# su-exec compatible shim over setpriv: like su-exec and gosu, it sets HOME
# to the target user's home (setpriv alone keeps the caller's, e.g. /root).
write_privilege_shim() {
    cat > "$1" <<'SHIM'
#!/bin/sh
# su-exec compatible: <user>[:<group>] <command> [args...]
set -e
spec="$1"; shift
user="${spec%%:*}"
if [ "$user" != "$spec" ]; then group="${spec#*:}"; else group="$(id -gn "$user")"; fi
home="$(getent passwd "$user" | cut -d: -f6)"
if [ -n "$home" ]; then HOME="$home"; export HOME; fi
exec setpriv --reuid="$(id -u "$user")" --regid="$(getent group "$group" | cut -d: -f3)" --init-groups -- "$@"
SHIM
    chmod 755 "$1"
}

# Writes the `<agent>-as-agent` shim: what the root-run setup wrapper execs
# instead of the provider entrypoint. It gives up root first, so the whole
# entrypoint (its chown, mkdir, cp and config fixes) runs as the agent user,
# and nothing is "synced back" as root afterwards. Refreshed tokens leave the
# Sprite only through the launcher's export directory.
write_agent_shim() {
    local entry_dir="$1" agent="$2" bin_dir="$3"
    cat > "$entry_dir/$agent-as-agent" <<SHIM
#!/bin/bash
# Generated by sprites-agent-setup.sh: runs the $agent entrypoint as the unprivileged agent user.
set -e
agent_path="$bin_dir:/home/node/.local/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
cd "\${PROPR_WORKSPACE:-/home/node/workspace}" 2>/dev/null || cd /home/node
runner=(env HOME=/home/node USER=node LOGNAME=node PATH="\$agent_path" "$entry_dir/$agent-entrypoint.sh")
if [ "$agent" = "antigravity" ] && [ "\${PROPR_EPHEMERAL_STATE:-0}" = "1" ]; then
    # The entrypoint prepares the disposable HOME as the agent user; the CLI then runs with it.
    runner+=(env HOME=/tmp/propr-antigravity-home)
fi
if [ "\$(id -u)" = "0" ]; then exec su-exec node "\${runner[@]}" "\$@"; fi
exec "\${runner[@]}" "\$@"
SHIM
    chmod 0755 "$entry_dir/$agent-as-agent"
}

# Installs the provider entrypoints, unchanged, into <entry dir> (root-owned)
# with their `<agent>-as-agent` shims.
install_entrypoints() {
    local source_dir="$1" entry_dir="$2" bin_dir="$3" agent
    install -d -m 0755 "$entry_dir"
    for agent in claude codex antigravity; do
        install -m 0755 "$source_dir/$agent-entrypoint.sh" "$entry_dir/$agent-entrypoint.sh"
        write_agent_shim "$entry_dir" "$agent" "$bin_dir"
    done
}

# Whether <user> can modify neither <path> nor any directory above it.
beyond_user_control() {
    local user="$1" path="$2" uid groups current mode
    uid="$(id -u "$user")" || return 1
    groups=" $(id -G "$user") "
    for current in "$path" "$(readlink -f -- "$path")"; do
        while :; do
            [ -e "$current" ] || [ -L "$current" ] || return 1
            [ "$(stat -c %u -- "$current")" != "$uid" ] || return 1
            mode="$(stat -c %a -- "$current")"
            (( (8#$mode & 8#002) == 0 )) || [ -L "$current" ] || return 1
            if (( (8#$mode & 8#020) != 0 )) && [ ! -L "$current" ]; then
                case "$groups" in *" $(stat -c %g -- "$current") "*) return 1 ;; esac
            fi
            [ "$current" != / ] || break
            current="$(dirname -- "$current")"
        done
    done
}

# Sourcing the script (the unit tests do) only defines the functions above.
if [ "${BASH_SOURCE[0]}" != "$0" ]; then return 0; fi

source_dir="${1:?usage: sprites-agent-setup.sh <directory with the setup files>}"
: "${CLAUDE_CLI_VERSION:?CLAUDE_CLI_VERSION is required}"
: "${CODEX_CLI_VERSION:?CODEX_CLI_VERSION is required}"
: "${ANTIGRAVITY_CLI_VERSION:?ANTIGRAVITY_CLI_VERSION is required}"
: "${ANTIGRAVITY_CLI_RELEASE_ID:?ANTIGRAVITY_CLI_RELEASE_ID is required}"
: "${ANTIGRAVITY_CLI_SHA512:?ANTIGRAVITY_CLI_SHA512 is required}"
: "${PROPR_SPRITES_SETUP_HASH:?PROPR_SPRITES_SETUP_HASH is required}"

[ "$(id -u)" = "0" ] || die "must run as root (sudo -n)"
# The launcher reads NUL-separated records with mapfile -d (bash 4.4+).
[ "${BASH_VERSINFO[0]}" -gt 4 ] || { [ "${BASH_VERSINFO[0]}" -eq 4 ] && [ "${BASH_VERSINFO[1]}" -ge 4 ]; } || die "bash 4.4 or later is required"
link_sprite_node /.sprite/bin/node /usr/local/bin
for tool in node npm git curl tar sha512sum stat install useradd sed readlink setsid tail head timeout; do
    command -v "$tool" >/dev/null 2>&1 || die "required tool $tool is missing on this Sprite"
done

prefix=/opt/propr
bin_dir="$prefix/bin"
npm_prefix="$prefix/npm"
entry_dir="$prefix/entrypoints"
run_dir="$prefix/run"
# The identity the Sprites filesystem API writes as: it uploaded the setup files.
upload_owner="$(stat -c %u:%g -- "$source_dir")"
mkdir -p "$bin_dir" "$npm_prefix"
chown root:root "$prefix" "$bin_dir"
chmod 755 "$prefix" "$bin_dir"

# --- node user -----------------------------------------------------------
if ! id node >/dev/null 2>&1; then
    useradd --create-home --home-dir /home/node --shell /bin/bash --user-group node
fi
[ "$(id -u node)" != "0" ] || die "the node user must not be root"
[ "$(getent passwd node | cut -d: -f6)" = "/home/node" ] || die "the node user's home must be /home/node"
for group in sudo wheel admin; do gpasswd -d node "$group" >/dev/null 2>&1 || true; done
rm -f /etc/sudoers.d/node
mkdir -p /home/node/workspace /home/node/.local/bin
chown node:node /home/node /home/node/workspace /home/node/.local /home/node/.local/bin
chmod 755 /home/node

# --- privilege drop ------------------------------------------------------
if ! command -v su-exec >/dev/null 2>&1; then
    if command -v gosu >/dev/null 2>&1; then ln -sf "$(command -v gosu)" /usr/local/bin/su-exec
    else command -v setpriv >/dev/null 2>&1 || die "neither su-exec, gosu nor setpriv is available"; write_privilege_shim /usr/local/bin/su-exec; fi
fi
command -v gosu >/dev/null 2>&1 || ln -sf "$(command -v su-exec)" /usr/local/bin/gosu
[ "$(su-exec node id -u)" = "$(id -u node)" ] || die "su-exec cannot drop to the node user"
if su-exec node sudo -n true >/dev/null 2>&1; then die "the node user must not have sudo"; fi

# --- pinned CLIs ---------------------------------------------------------
pin_npm_cli @anthropic-ai/claude-code "$CLAUDE_CLI_VERSION" claude
pin_npm_cli @openai/codex "$CODEX_CLI_VERSION" codex

if [ "$(installed_version "$bin_dir/agy")" != "$ANTIGRAVITY_CLI_VERSION" ]; then
    log "installing Antigravity CLI $ANTIGRAVITY_CLI_VERSION"
    work="$(mktemp -d)"
    object="antigravity-cli/${ANTIGRAVITY_CLI_VERSION}-${ANTIGRAVITY_CLI_RELEASE_ID}/linux-x64/cli_linux_x64.tar.gz"
    downloaded=""
    for url in "https://storage.googleapis.com/antigravity-public/$object" \
        "https://storage.googleapis.com/download/storage/v1/b/antigravity-public/o/${object//\//%2F}?alt=media"; do
        if curl --fail --show-error --silent --location --connect-timeout 20 --max-time 300 --retry 5 --retry-all-errors -o "$work/agy.tar.gz" "$url"; then
            downloaded=1
            break
        fi
    done
    [ -n "$downloaded" ] || die "could not download the Antigravity CLI"
    # The SHA-512 pin is the trust boundary, whichever route served the archive.
    echo "${ANTIGRAVITY_CLI_SHA512}  $work/agy.tar.gz" | sha512sum -c - >&2
    [ "$(tar -tzf "$work/agy.tar.gz")" = antigravity ] || die "unexpected Antigravity CLI archive layout"
    tar -xzf "$work/agy.tar.gz" -C "$work" antigravity
    install -m 0755 "$work/antigravity" "$bin_dir/agy"
    rm -rf "$work"
fi
[ "$(installed_version "$bin_dir/agy")" = "$ANTIGRAVITY_CLI_VERSION" ] || die "agy is not at the pinned version $ANTIGRAVITY_CLI_VERSION"
# Where the image has it.
ln -sf "$bin_dir/agy" /home/node/.local/bin/agy

# --- entrypoints, launcher and run directory -----------------------------
install -m 0755 "$source_dir/gh-wrapper.sh" /usr/local/bin/gh-wrapper
install_entrypoints "$source_dir" "$entry_dir" "$bin_dir"
install -m 0755 -o root -g root "$source_dir/sprites-launcher.sh" "$prefix/launcher.sh"
# Each run's payload is uploaded here through the filesystem API; the agent user can neither read nor enter it.
rm -rf "$run_dir"
install -d -m 0700 "$run_dir"
chown "$upload_owner" "$run_dir"
# Everything root executes for a run, and every directory above it, must stay out of the agent user's reach.
for path in "$prefix/launcher.sh" "$entry_dir"/* "$bin_dir" "$npm_prefix" /usr/local/bin/gh-wrapper "$(command -v su-exec)" "$(command -v gosu)" "$run_dir"; do
    beyond_user_control node "$path" || die "the node user can modify $path or a directory above it, so it could replace what root runs"
done

# The image's git configuration for the agent user (HOME is explicit: setup runs under sudo with root's).
for setting in "user.name=ProPR Agent Bot" "user.email=agent-bot@propr.dev" "init.defaultBranch=main"; do
    su-exec node env HOME=/home/node git config --global "${setting%%=*}" "${setting#*=}"
done
su-exec node env HOME=/home/node git config --global --replace-all safe.directory '*'

# The uploaded setup files are not part of the clean checkpoint.
rm -rf -- "$source_dir"
printf '%s\n' "$PROPR_SPRITES_SETUP_HASH" > "$prefix/sprites-setup.hash"
log "ready ($PROPR_SPRITES_SETUP_HASH)"
