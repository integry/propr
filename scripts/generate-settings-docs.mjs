import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { SETTINGS_CATALOG } from '../packages/api/mcp/settingsCatalog.ts';

const scopeLabels = {
  instance: 'Instance settings',
  repository: 'Repository settings',
  user: 'User settings',
  environment: 'Environment settings',
};

const cell = value => String(value ?? '—').replaceAll('|', '\\|').replaceAll('\n', ' ');
const code = value => value ? `\`${cell(value)}\`` : '—';
const tools = entry => [
  entry.mcp?.read && `read: \`${entry.mcp.read}\``,
  entry.mcp?.write && `write: \`${entry.mcp.write}\``,
].filter(Boolean).join('<br />') || entry.mcpStatus.replaceAll('_', ' ');

export function renderSettingsLocations(catalog = SETTINGS_CATALOG) {
  const lines = [
    '---',
    'title: Where Each Setting Lives',
    'sidebar_position: 11',
    '---',
    '',
    '{/* Generated by npm run docs:settings. Do not edit by hand. */}',
    '',
    'Use the MCP `find_setting` tool to search this same catalog by setting name, alias, or environment variable. The catalog describes locations only; it never exposes credential values.',
    '',
  ];
  for (const scope of Object.keys(scopeLabels)) {
    const entries = catalog.filter(entry => entry.scope === scope);
    lines.push(`## ${scopeLabels[scope]}`, '');
    lines.push('| Setting | UI | MCP | CLI | Environment | Restart | Notes |');
    lines.push('|---|---|---|---|---|---|---|');
    for (const entry of entries) {
      const label = `**${cell(entry.label)}**<br />${code(entry.id)}`;
      const environment = entry.env?.map(code).join('<br />') || '—';
      const reference = entry.docs ? ` [Reference](./${entry.docs.split('/').at(-1)}.md).` : '';
      lines.push(`| ${label} | ${cell(entry.ui)} | ${tools(entry)} | ${code(entry.cli)} | ${environment} | ${entry.restartRequired ? 'Yes' : 'No'} | ${cell(entry.reason ?? '')}${reference} |`);
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

const invokedPath = process.argv[1] && pathToFileURL(process.argv[1]).href;
if (import.meta.url === invokedPath) {
  const root = dirname(dirname(fileURLToPath(import.meta.url)));
  const target = join(root, 'docs/docs/operations/settings-locations.md');
  await writeFile(target, renderSettingsLocations());
  console.log(`Generated ${target}`);
}
